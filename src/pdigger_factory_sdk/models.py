            tray=p.req("tray", as_int),
            ref=p.req("ref", SpeckleRef.from_json),
            at=p.req("at", SpeckleAt.from_json),
            device=p.req("device", as_str),
            gpu_ms=p.req("gpu_ms", as_num),
            wall_ms=p.req("wall_ms", as_num),
