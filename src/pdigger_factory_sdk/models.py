@dataclass(slots=True, kw_only=True)
class StoneLook:
    """The stone's look: the band-pass texture of its face, for telling stones apart by appearance (fixer thin-v1: on
    every camera, the recordings and the plant cameras, unless its catalog entry's stone model turns
    `thin.lookOut` off). It is read on a still board's frame (a packet the world host reads image evidence for)
    while the stone rests confirmed and frozen, untouched (not held, no touch for 10 packets, no hand point within
    its length, and no hand work on it that a later check has not yet read it present after) and in clear view
    (the person mask on at most 10 % of its outline and face). It is sent only in the world of the packet `g` it
    was read on (and that packet's revisions, `rev`), and read again 100 packets later, or once a hand touched or
    put the stone down since, or once its face moved 4 proxy px, turned 3 degrees or changed a side by 15 %; at
    most 16 stones a packet. Keep the latest look of each stone. Format `v` 1. The proxy grey (the engine's frame,
    `px` x native px) is band-passed by a difference of Gaussians, sigma 1 minus sigma 3 proxy px (kernels to 3
    sigma). The face `at` (proxy px; `theta` its long side's angle, radians, x right and y down) carries a grid of
    `nu` x `nv` cells at a fixed pitch `sp` proxy px, centred on the face: cell (i, j) lies at u = (i - (nu - 1) /
    2) sp along the long side and v = (j - (nv - 1) / 2) sp across it, the proxy point (cx + u cos theta - v sin
    theta, cy + u sin theta + v cos theta), read bilinearly. nu = max(3, floor(fL L / sp) + 1), nv = max(3,
    floor(fS S / sp) + 1), with (fL, fS) = (.7, .7) for a `rect` face and (.7, .5) for a `dogbone` face. The read
    cells are z-normalised (their own mean and standard deviation) and stored as int8 round(z q), clamped to
    [-127, 127]; -128 marks a cell not read (its kernels leave the frame). `d` holds the cells as base64 (RFC
    4648, padded) of nu x nv bytes, row j after row j - 1, cell i after cell i - 1 (two's complement). A pitch
    fixed in px keeps the grid's cells on the same texture when a refit changes L or S. The angle is a long
    side's, so a stone may read half a turn round (a near-square one a quarter turn too): compare looks over those
    turns and a few cells of shift.
    """

    v: int
    """Format version."""
    g: int
    """The packet whose frame it was read on."""
    sp: float
